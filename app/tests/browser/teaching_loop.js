async (page) => {
  await page.goto('http://127.0.0.1:8767/');
  await page.getByRole('button',{name:'师生任务',exact:true}).click();
  const errors=[];
  page.on('pageerror', error=>errors.push(String(error)));
  await page.getByLabel('任务标题',{exact:true}).fill('逆运算任务');
  await page.getByLabel('教学目标 / 教材材料说明').fill('等式两边同时减去1并验根');
  await page.getByRole('button',{name:'依据目标起草练习',exact:true}).click();
  await page.getByText('草案已生成。请检查每题原题与目标后发布。').waitFor();
  await page.getByRole('button',{name:'检查完毕，发布任务 →',exact:true}).click();
  await page.getByText('任务已发布，学生可以从右侧领取题目。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'学生 · 领取并作答 →',exact:true}).waitFor();
  const original=await page.getByLabel('已发布任务').inputValue();
  await page.getByRole('button',{name:'学生 · 领取并作答 →',exact:true}).click();
  await page.waitForFunction(()=>document.getElementById('problem').value==='解 x+1=2。');
  if(await page.getByLabel('原题 保留完整条件与范围').inputValue()!=='解 x+1=2。')throw Error('Task problem not carried to student form');
  await page.getByLabel('我的解题过程 建议每一步另起一行').fill('x=3');
  let completed=page.waitForResponse(async response=>response.url().includes('/api/submissions/')&&response.request().method()==='GET'&&(await response.json()).state==='ready');
  await page.getByRole('button',{name:'开始检查 →',exact:true}).click();await completed;
  await page.getByRole('button',{name:'师生任务',exact:true}).click();
  await page.getByText('当前过程有错',{exact:true}).waitFor();
  await page.getByRole('button',{name:'依据当前诊断起草补救教案',exact:true}).click();
  await page.getByText('教案草稿已生成，先审阅再交给备课或布置再练习。').waitFor();
  await page.getByRole('button',{name:'交给教师备课 →',exact:true}).click();
  await page.getByText('已带入学习证据和教师草稿；请补齐年级、教材、课时，再生成大纲。').waitFor();
  if(!(await page.getByLabel('教案内容').inputValue()).includes('逆运算补救课'))throw Error('Plan not transferred to lesson studio');
  await page.getByRole('button',{name:'师生任务',exact:true}).click();
  await page.getByRole('button',{name:'布置关联的再练习 →',exact:true}).click();
  await page.getByText('将关联前序任务 '+original.slice(0,8)+' 及当前证据版本。',{exact:true}).waitFor();
  await page.getByLabel('原题',{exact:true}).fill('解 x+2=4。');
  await page.getByRole('button',{name:'检查完毕，发布任务 →',exact:true}).click();
  await page.getByText('关联前序任务：'+original.slice(0,8),{exact:true}).waitFor();
  await page.getByLabel('已发布任务').selectOption(original);
  await page.getByText('当前过程有错',{exact:true}).waitFor();
  await page.getByRole('button',{name:'学生 · 继续修订 →',exact:true}).click();
  await page.getByText(/来自教学任务：/).waitFor();
  await page.getByLabel('我的解题过程 建议每一步另起一行').fill('x=1');
  completed=page.waitForResponse(async response=>response.url().includes('/api/submissions/')&&response.request().method()==='GET'&&(await response.json()).state==='ready');
  await page.getByRole('button',{name:'开始检查 →',exact:true}).click();await completed;
  await page.getByRole('button',{name:'师生任务',exact:true}).click();
  await page.getByText('当前过程正确',{exact:true}).waitFor();
  await page.getByText('学生提交或诊断已经变化，这份教案依据已过期；请重新规划。',{exact:true}).waitFor();
  if(!await page.getByRole('button',{name:'交给教师备课 →',exact:true}).isDisabled())throw Error('Stale plan is usable');
  await page.setViewportSize({width:1280,height:900});
  await page.screenshot({path:'output/playwright/teaching-loop-desktop.png',fullPage:true});
  const desktop=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'output/playwright/teaching-loop-mobile.png',fullPage:true});
  const mobile=await page.evaluate(()=>({width:innerWidth,scroll:document.documentElement.scrollWidth}));
  if(desktop.scroll>desktop.width||mobile.scroll>mobile.width)throw Error('Horizontal overflow '+JSON.stringify({desktop,mobile}));
  if(errors.length)throw Error(errors.join('\n'));
  return {passed:true,model:'explicit fixture backend',flow:'design,publish,student submission,teacher evidence,remedial plan,lesson handoff,followup,revision,stale plan rejection',desktop,mobile,errors};
}
